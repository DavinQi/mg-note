import { asBlob } from 'html-docx-js-typescript';
import JSZip from 'jszip';
import mammoth from 'mammoth';

function parseMhtToHtml(mht: string): string {
  const parts = mht.split(/------=[a-zA-Z0-9_-]+/);
  let html = '';
  const images: Record<string, string> = {};

  for (const part of parts) {
    if (part.includes('Content-Type: text/html')) {
      const idx = part.indexOf('\n\n');
      const body = idx !== -1 ? part.slice(idx + 2) : part;
      // Decode quoted-printable
      html = body.replace(/=\r?\n/g, '').replace(/=3D/g, '=');
    } else if (part.includes('Content-Type: image/')) {
      const typeMatch = part.match(/Content-Type:\s*(image\/[a-zA-Z0-9+.-]+)/i);
      const locMatch = part.match(/Content-Location:\s*([^\r\n]+)/i);
      const mime = typeMatch ? typeMatch[1] : 'image/png';
      const loc = locMatch ? locMatch[1].trim() : '';
      const idx = part.indexOf('\n\n');
      const base64Data = idx !== -1 ? part.slice(idx + 2).replace(/\s+/g, '') : '';
      if (loc && base64Data) {
        images[loc] = `data:${mime};base64,${base64Data}`;
      }
    }
  }

  for (const [loc, dataUrl] of Object.entries(images)) {
    html = html.split(loc).join(dataUrl);
  }

  return html;
}

export async function docxBytesToHtml(bytes: Uint8Array | number[]): Promise<string> {
  const uint8 = bytes instanceof Uint8Array ? bytes : new Uint8Array(bytes);
  if (uint8.byteLength === 0) return '<p><br></p>';

  const arrayBuffer = uint8.buffer.slice(
    uint8.byteOffset,
    uint8.byteOffset + uint8.byteLength
  ) as ArrayBuffer;

  // First check if it is an AltChunk docx (generated by html-docx-js)
  try {
    const zip = await JSZip.loadAsync(arrayBuffer);
    const afchunkFile = zip.file('word/afchunk.mht');
    if (afchunkFile) {
      const mht = await afchunkFile.async('string');
      const parsedHtml = parseMhtToHtml(mht);
      if (parsedHtml.trim()) return parsedHtml;
    }
  } catch (_) {
    // If JSZip fails, continue to mammoth
  }

  // Standard Word document (document.xml) parsed via mammoth
  try {
    const result = await mammoth.convertToHtml({ arrayBuffer });
    return result.value || '<p><br></p>';
  } catch (err) {
    console.error('Mammoth docx parse failed:', err);
    return '<p><br></p>';
  }
}

export async function htmlToDocxBytes(html: string): Promise<number[]> {
  const content = html || '<p><br></p>';
  const docxBlob = await asBlob(content);

  let arrayBuffer: ArrayBuffer;
  if (docxBlob instanceof Blob) {
    arrayBuffer = await docxBlob.arrayBuffer();
  } else if (docxBlob instanceof ArrayBuffer) {
    arrayBuffer = docxBlob;
  } else {
    arrayBuffer = new Uint8Array(docxBlob as any).buffer as ArrayBuffer;
  }

  return Array.from(new Uint8Array(arrayBuffer));
}
